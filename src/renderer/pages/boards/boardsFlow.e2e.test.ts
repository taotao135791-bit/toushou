import { spawnSync } from 'node:child_process'
import { mkdtempSync, rmSync, existsSync, readFileSync, writeFileSync } from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { createRequire } from 'node:module'
import { describe, expect, it } from 'vitest'

const require_ = createRequire(import.meta.url)
describe('board creation flow in Electron', () => {
  it('opens boards and preserves scoped, anonymized readings', { timeout: 120000 }, async () => {
    const dir = mkdtempSync(path.join(os.tmpdir(), 'boards-flow-'))
    try {
      const root = path.dirname(require_.resolve('electron/package.json'))
      const electron = process.platform === 'win32' ? path.join(root, 'dist/electron.exe') : process.platform === 'darwin' ? path.join(root, 'dist/Electron.app/Contents/MacOS/Electron') : path.join(root, 'dist/electron')
      if (!existsSync(electron)) throw new Error('Electron unavailable')
      let build: { buildSync: (opts: Record<string, unknown>) => unknown }
      try { build = require_('esbuild') } catch { build = require_(path.join(path.dirname(require_.resolve('vite/package.json')), '..', 'esbuild')) }
      build.buildSync({ entryPoints: [path.resolve(__dirname, 'boardsFlow.fixture.tsx')], outfile: path.join(dir, 'fixture.js'), bundle: true, platform: 'browser', format: 'iife', jsx: 'automatic', loader: { '.css': 'empty' }, alias: { '@shared': path.resolve(__dirname, '../../../shared') } })
      const postcss = require_('postcss')
      const cssPath = path.resolve(__dirname, '../../index.css')
      const css = await postcss([require_('tailwindcss')(), require_('autoprefixer')()]).process(readFileSync(cssPath, 'utf8'), { from: cssPath })
      writeFileSync(path.join(dir, 'fixture.css'), css.css)
      const env = { ...process.env }; delete env.ELECTRON_RUN_AS_NODE
      const result = spawnSync(electron, [path.resolve(__dirname, 'boardsFlow.harness.cjs'), dir], { encoding: 'utf8', timeout: 90000, env })
      const line = result.stdout?.split('\n').find(s => s.startsWith('E2E_RESULT '))
      expect(line, result.stderr).toBeDefined()
      const data = JSON.parse(line!.slice('E2E_RESULT '.length))
      expect(data, `${result.stdout}\n${result.stderr}`).not.toHaveProperty('fatal')
      expect(data.initial).toMatchObject({ today: true, activeBoard: null, toolbar: false, menu: false })
      expect(data.initialTodayReads).toBe(0)
      expect(data.created).toMatchObject({ today: false, activeBoard: 'TikTok panorama', toolbar: true, menu: true, ttNotice: true, noReading: false, connect: true })
      expect(data.created.saved[0]).toMatchObject({ name: 'TikTok panorama', types: expect.arrayContaining(['tt-reading', 'counter', 'chart-line']) })
      expect(data.created.saved[0]).toMatchObject({ masterScope: { range: 'last7' }, verifiedCards: 7 })
      expect(data.verified[0]).toContain('5')
      expect(data.verified[0]).not.toContain('700')
      expect(data.verified[0]).not.toContain('100')
      expect(data.failedReload).toContain('Waiting for a complete TikTok reading')
      expect(data.noSuccessfulAccounts).toEqual({ value: '—', failed: true, unattempted: true })
      expect(data.progress).toBe(true)
      expect(data.cancelled).toMatchObject({ notice: true })
      expect(data.cancelled.count).toBeGreaterThan(0)
      expect(data.unverified).toContain('Waiting for a complete TikTok reading')
      expect(data.unverified).not.toContain('700')
      expect(data.connect.route).toBe('/connections')
      expect(data.returned).toMatchObject({ today: true, activeBoard: null, toolbar: false, menu: false })
      expect(data.returnedTodayReads).toBe(0)
      expect(data.searchById).toHaveLength(1)
      expect(data.searchById[0]).toContain('7300000000000000002')
      expect(data.searchByName).toHaveLength(2)
      expect(data.searchByName[0]).toContain('Fixture Shared')
      expect(data.searchByName[0]).toContain('7300000000000000001')
      expect(data.searchByName[1]).toContain('7300000000000000002')
      expect(data.keyboardActive).toBe(true)
      expect(data.chosenAccountId).toBe('7300000000000000001')
      expect(data.readsBeforeSubmit).toBe(0)
      expect(data.singleScopeRetries).toHaveLength(2)
      expect(data.singleScopeRetries.every((request: { advertiserId?: string }) => request.advertiserId === '7300000000000000001')).toBe(true)
      expect(data.singleDateSwitch).toMatchObject({ range: 'today', advertiserId: '7300000000000000001' })
      expect(data.todayProgress).toBe(true)
      expect(data.todayPartial).toEqual({ visible: true, spend: true, expired: false })
      expect(data.todayCancelled).toEqual({ notice: true, completed: true, unread: true })
      expect(data.singleRefresh.input.advertiserId).toBe('7300000000000000001')
      expect(data.singleRefresh.a).toContain('15.00')
      expect(data.singleRefresh.b).toContain('77.00')
      expect(data.failedSingle.text).toContain('15.00')
      expect(data.failedSingle.text).toContain('previous reading and its original time')
      expect(data.failedSingle.disabled).toBe(true)
      expect(data.switchedSingle.a).toContain('44.00')
      expect(data.switchedSingle.b).toContain('88.00')
      expect(data.switchedSingle.last).toMatchObject({ range: 'today' })
      expect(data.switchedSingle.last).not.toHaveProperty('advertiserId')
      expect(data.switchedSingle.a).not.toContain('15.00')
      expect(data.overallDraft.existingDraft).toBe('existing unsent draft')
      expect(data.overallDraft.autosend).toBe(true)
      expect(data.overallDraft.mode).toBe('readonly')
      for (const account of ['PRIVATE_ACCOUNT_A', 'PRIVATE_ACCOUNT_B', '7300000000000000001', '7300000000000000002']) expect(data.overallDraft.text).toContain(account)
      expect(data.singleDraft.autosend).toBe(true)
      expect(data.singleDraft.existingDraft).toBe('existing unsent draft')
      expect(data.singleDraft.mode).toBe('readonly')
      expect(data.singleDraft.text).toContain('PRIVATE_ACCOUNT_A')
      expect(data.singleDraft.text).toContain('7300000000000000001')
      expect(data.singleDraft.text).not.toContain('PRIVATE_ACCOUNT_B')
      expect(data.singleDraft.text).not.toContain('7300000000000000002')
      expect(data.firstCustom).toMatchObject({ range: 'custom', startDate: data.customResult.first.start, endDate: data.customResult.first.end })
      expect(data.latestCustom).toMatchObject({ range: 'custom', startDate: data.customResult.next.start, endDate: data.customResult.next.end })
      expect(data.customResult.a).toContain('44.00')
      expect(data.customResult.b).toContain('88.00')
      expect(data.customResult.a).not.toContain('999.00')
      expect(data.resultFilter).toEqual({ a: true, b: false, scopeNotice: true })
      expect(data.chartInitially).toBe(true)
      expect(data.failedSnapshot).toEqual({ error: true, dialog: true, a: true, b: true, chart: true })
      expect(data.savedSnapshot).toMatchObject({ activeBoard: 'Snapshot fixture', chart: true, accountCount: 2, table: true, svg: false, fixedDateNote: true, masterToolbar: false, noModulesNotice: false, cachedNotice: false })
      expect(data.savedSnapshot.groupHeadings).toEqual(expect.arrayContaining(['TikTok · USD', 'TikTok · EUR']))
      expect(data.exportedSnapshot).toMatchObject({ anonymized: true, table: true, svg: false, script: false, containsPrivate: false })
      expect(data.exportedSnapshot.groups).toEqual(expect.arrayContaining([
        { heading: 'TikTok · USD', accounts: ['Account 1'] },
        { heading: 'TikTok · EUR', accounts: ['Account 2'] }
      ]))
      expect(data.exportedSnapshot.groups).toHaveLength(2)
      expect(data.editorial).toContain('Weekly report')
      expect(data.operations).toContain('Account inspection')
      expect(data.minimal).toContain('Reading snapshot')
      expect(data.editorInitiallyNoCode).toBe(true)
      expect(data.aiFailure).toMatchObject({ instruction: 'Make the report clear', calls: 1, revision: 1, inputKeys: ['expectedRevision', 'id', 'instruction', 'requestId'] })
      expect(data.aiCancel).toEqual({ instruction: 'Make the report clear', cancels: 1, calls: 2 })
      expect(data.aiClose).toEqual({ instruction: 'Make the report clear', cancels: 2, calls: 3 })
      expect(data.aiPreview).toMatchObject({ visible: true, boundValue: true, noSvg: true, savedUnchanged: true, revision: 1, saveDisabled: true, exportDisabled: true })
      expect(data.aiPreview.chartGroups).toEqual(expect.arrayContaining([
        expect.stringMatching(/^TikTok · USD · \d{4}-\d{2}-\d{2} – \d{4}-\d{2}-\d{2} · Timezone group \d+$/),
        expect.stringMatching(/^TikTok · EUR · \d{4}-\d{2}-\d{2} – \d{4}-\d{2}-\d{2} · Timezone group \d+$/)
      ]))
      expect(data.aiPreview.chartGroups).toHaveLength(2)
      expect(data.aiSaveFailed).toEqual({ savedUnchanged: true, revision: 1, previewStillVisible: true, canRetry: true, calls: 4 })
      expect(data.aiSaved).toEqual({ saved: true, revision: 2 })
      expect(data.appendConflict).toEqual({ dialog: true, widgets: 1 })
      expect(data.appendExisting).toMatchObject({ boards: 1, tabs: 1, widgets: 2, originalPreserved: true })
      expect(data.appendExisting.newWidget).toBe(data.appendExisting.editorWidget)
      expect(data.modularDefault).toBe(true)
      expect(data.modularAiTarget.source).toBe(data.modularAiTarget.expected)
      expect(data.modularAiTarget.source).toBeTruthy()
      expect(data.modularLayout.types).toContain('reading-snapshot')
      expect(data.modularLayout.kinds).toEqual(expect.arrayContaining(['coverage', 'spend-chart', 'note']))
      expect(data.modularLayout.count).toBeGreaterThanOrEqual(4)
      expect(data.modularLayout.unique).toBe(data.modularLayout.count)
      expect(data.modularLayout.sideBySide).toBe(true)
      expect(data.modularLayout.firstWidth / data.modularLayout.gridWidth).toBeGreaterThan(0.4)
      expect(data.modularLayout.secondWidth / data.modularLayout.gridWidth).toBeGreaterThan(0.4)
      expect(data.modularLayout.frameWidth).toBeGreaterThan(100)
      expect(data.modularLayout.frameHeight).toBeGreaterThan(100)
      expect(data.modularLayout.sandbox).toBe('')
      expect(data.modularLayout.tailwind).toBe('flex')
      expect(data.fullPreview).toMatchObject({ sandbox: '', noScript: true, hasClose: true })
      expect(data.fullPreview.width).toBeGreaterThan(600)
      expect(data.fullPreview.height).toBeGreaterThan(500)
      expect(data.modularManipulation).toMatchObject({ count: data.modularLayout.count, source: true, resized: true })
      expect(data.fastResize).toBe(true)
      expect(data.dimensionsConflict).toEqual({ width: '3', height: '7', visible: true })
      expect(data.exactDimensions).toEqual({ width: 3, height: 7, source: true })
      expect(data.chatPreview).toMatchObject({ sandbox: '', content: true, hasOpen: true, notice: true, outsideToolGroup: true })
      expect(data.chatPreview.width).toBeGreaterThan(200)
      expect(data.chatPreview.height).toBeGreaterThanOrEqual(400)
      expect(data.previewNavigation).toBe('Existing board')
      expect(data.staleLoadIgnored).toBe(true)
      expect(data.editorPreview).toEqual({ html: true, table: true, anonymous: true, unsavedExportBlocked: true, unsavedGenerateBlocked: true })
      expect(data.editorExport).toEqual({ revision: 3, html: true, anonymous: true, css: true })
      expect(data.editorReopen).toEqual({ html: '<h1>Custom fixture title</h1><div data-reading-slot></div><p>Reviewed</p>', css: 'h1 { color: #123456; }' })
      expect(data.savedLayoutVisible).toBe(true)
      expect(data.savedCardExport).toEqual({ custom: true, oldSnapshot: false, anonymous: true })
      expect(data.highlightDraft.existingDraft).toBe('existing unsent draft')
      expect(data.highlightDraft.autosend).toBe(true)
      expect(data.highlightDraft.mode).toBe('readonly')
      expect(data.highlightDraft.text).toContain('board-highlights')
      expect(data.highlightDraft.text).toContain('PRIVATE_ACCOUNT_A')
      expect(data.highlightDraft.text).toContain('7300000000000000001')
      expect(data.malformedHighlight).toBe(true)
      expect(data.staleHighlight).toBe(true)
      expect(data.failedHighlight).toBe(true)
      expect(data.highlightEvidenceLabel).toContain('PRIVATE_ACCOUNT_A')
      expect(data.highlightEvidenceLabel).toContain('7300000000000000001')
      expect(data.appliedHighlight).toBe(true)
      expect(data.highlightEvidenceNavigation).toEqual({ route: '/boards', focused: '1', board: 'Snapshot fixture' })
      expect(data.returnToLayout).toBe(true)
      expect(data.blank).toMatchObject({ today: false, activeBoard: 'Blank fixture', toolbar: true, menu: true })
      expect(data.blank.saved[2]).toMatchObject({ name: 'Blank fixture', types: [] })
      expect(data.composed).toMatchObject({ today: false, activeBoard: 'Blank board', toolbar: true, menu: true })
      expect(data.composed.saved).toHaveLength(4)
      expect(data.googleVisible, JSON.stringify(data.googleDiagnostics)).toEqual({ scrolled: true, cardVisible: true, inputVisible: true, focused: true })
      expect(data.ttVisible, JSON.stringify(data.ttDiagnostics)).toEqual({ scrolled: true, cardVisible: true, inputVisible: true, focused: true })
      expect(data.switchedAway).toEqual({ today: true, focusedInConfig: false })
      expect(data.aiBoardCreated).toMatchObject({ savedDelta: 1, savedBoard: 'AI board fixture', draft: 'existing unsent draft', autosend: true, modelCalls: 4 })
      expect(data.aiBoardCreated.sourceBoard).toBe(data.aiBoardCreated.boardId)
    } finally { rmSync(dir, { recursive: true, force: true }) }
  })
})
